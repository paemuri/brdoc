package brdoc

import (
	"testing"
)

func TestIsPixBRCode(t *testing.T) {
	t.Run("rejects invalid data", func(t *testing.T) {
		assertInvalidCases(t, IsPixBRCode, []docCase{
			{"empty", ""},
			{"letters", "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA"},
			{"truncated", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053039865802BR5913Fulano de Tal6008BRASILIA62070503*"},
		})
	})

	// Examples of the manual of Pix.
	t.Run("accepts the examples of the manual", func(t *testing.T) {
		assertValidCases(t, IsPixBRCode, []docCase{
			{"static", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***63041D3D"},
			{"dynamic", "00020101021226700014br.gov.bcb.pix2548pix.example.com/8b3da2f39a4140d1a91abd93113bd4415204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***630464E4"},
			{"composite with only the recurrence", "00020126180014br.gov.bcb.pix5204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***80740014br.gov.bcb.pix2552pix.example.com/rec/2353c790eefb11eaadc10242ac1200026304F2DA"},
			{"composite with a key", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053039865406100.505802BR5913Fulano de Tal6008BRASILIA62070503***80740014br.gov.bcb.pix2552pix.example.com/rec/2353c790eefb11eaadc10242ac12000263042875"},
			{"composite with a URL", "00020101021226700014br.gov.bcb.pix2548pix.example.com/8b3da2f39a4140d1a91abd93113bd4415204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***80740014br.gov.bcb.pix2552pix.example.com/rec/2353c790eefb11eaadc10242ac1200026304FB42"},
		})
	})

	// Calculated by hand, with valid CRCs.
	t.Run("accepts the optional fields", func(t *testing.T) {
		assertValidCases(t, IsPixBRCode, []docCase{
			{"amount, txid, additional information and withdrawal facilitator", "00020126970014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400000223Pagamento do pedido 1230308123456785204000053039865406123.455802BR5913Fulano de Tal6008BRASILIA62130509Pedido1236304FD70"},
			{"GUI in uppercase", "00020126580014BR.GOV.BCB.PIX0136123e4567-e12b-12d1-a456-4266554400005204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***6304F01B"},
			{"CRC in lowercase", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***63041d3d"},
			{"accents", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053039865802BR5913João da Silva6009São Paulo62070503***6304F05D"},
			{"other arrangements, from the example of the manual of BR Code with a valid txid", "00020104141234567890123426580014BR.GOV.BCB.PIX0136123e4567-e12b-12d1-a456-42665544000027300012BR.COM.OUTRO011001234567895204000053039865406123.455802BR5917NOME DO RECEBEDOR6008BRASILIA61087007490062180514RP12345678201980390012BR.COM.OUTRO01190123.ABCD.3456.WXYZ6304126F"},
		})
	})

	t.Run("rejects invalid CRCs", func(t *testing.T) {
		assertInvalidCases(t, IsPixBRCode, []docCase{
			{"wrong CRC", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***63040000"},
		})
	})

	// Calculated by hand, with valid CRCs.
	t.Run("rejects invalid fields", func(t *testing.T) {
		assertInvalidCases(t, IsPixBRCode, []docCase{
			{"payload format 02", "00020226580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***6304BAA3"},
			{"payload format not first", "26580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400000002015204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***63049CBC"},
			{"repeated ID", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-426655440000520400005204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***63044DB5"},
			{"point of initiation 13", "00020101021326580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***63047DC6"},
			{"no merchant category code", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-42665544000053039865802BR5913Fulano de Tal6008BRASILIA62070503***630405E3"},
			{"merchant category code with letters", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204ABCD53039865802BR5913Fulano de Tal6008BRASILIA62070503***630498BA"},
			{"currency 840", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053038405802BR5913Fulano de Tal6008BRASILIA62070503***63040C88"},
			{"amount with comma", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-42665544000052040000530398654041,005802BR5913Fulano de Tal6008BRASILIA62070503***6304B7EF"},
			{"country US", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053039865802US5913Fulano de Tal6008BRASILIA62070503***63048D48"},
			{"name with 26 characters", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053039865802BR5926AAAAAAAAAAAAAAAAAAAAAAAAAA6008BRASILIA62070503***63047F19"},
			{"city with 16 characters", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053039865802BR5913Fulano de Tal6016AAAAAAAAAAAAAAAA62070503***6304C14B"},
			{"no additional data", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053039865802BR5913Fulano de Tal6008BRASILIA6304740C"},
			{"txid with hyphen", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053039865802BR5913Fulano de Tal6008BRASILIA62140510Pedido-123630458CE"},
			{"txid with hyphen, from the example of the manual of BR Code", "00020104141234567890123426580014BR.GOV.BCB.PIX0136123e4567-e12b-12d1-a456-42665544000027300012BR.COM.OUTRO011001234567895204000053039865406123.455802BR5917NOME DO RECEBEDOR6008BRASILIA61087007490062190515RP12345678-201980390012BR.COM.OUTRO01190123.ABCD.3456.WXYZ6304AD38"},
			{"txid with 26 characters", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400005204000053039865802BR5913Fulano de Tal6008BRASILIA62300526AAAAAAAAAAAAAAAAAAAAAAAAAA6304601D"},
		})
	})

	// Calculated by hand, with valid CRCs.
	t.Run("rejects invalid fields of Pix", func(t *testing.T) {
		assertInvalidCases(t, IsPixBRCode, []docCase{
			{"no GUI of Pix", "00020126300012br.com.outro011001234567895204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***63043099"},
			{"merchant account without GUI", "00020126580014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-4266554400002714011001234567895204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***6304D64F"},
			{"key and URL", "00020126590014br.gov.bcb.pix0114+55619123456782519pix.example.com/abc5204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***63049CF1"},
			{"URL with protocol", "00020126780014br.gov.bcb.pix2556https://pix.example.com/8b3da2f39a4140d1a91abd93113bd4415204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***6304747C"},
			{"no key and no URL", "00020126180014br.gov.bcb.pix5204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***6304A335"},
			{"recurrence without URL", "00020126180014br.gov.bcb.pix5204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***80230014br.gov.bcb.pix0101x6304FD8A"},
			{"withdrawal facilitator with 7 characters", "00020126690014br.gov.bcb.pix0136123e4567-e12b-12d1-a456-426655440000030712345675204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***6304FB4D"},
		})
	})

	// Calculated by hand, with a valid CRC. Each type of key is tested by
	// TestIsPixKey.
	t.Run("rejects invalid keys", func(t *testing.T) {
		assertInvalid(t, IsPixBRCode,
			"00020126330014br.gov.bcb.pix0111123456789005204000053039865802BR5913Fulano de Tal6008BRASILIA62070503***6304D3E6",
		)
	})
}
